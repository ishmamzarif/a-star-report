#!/usr/bin/env python3
"""Run every search of the A* report and write its figures, tables and results.

Each number in the report's results comes out of this script, so what the
figures show is what the algorithms do.  Outputs, all in output/:

  map_graph.tex        the 64-district graph, Dhaka and Sylhet marked
  map_panels.tex       three panels: what each search expanded, and its route
  map_astar_rows.tex   table rows: the districts A* expanded, with g, h, f
  bddata.tex           g and h of all 64 districts, for the 3D map figures
  grid_orders.tex      expansion order and route of each search on the grid
  story_iso_*.tex      the eight-city example in an isometric view
  trace_original.tex   table rows: A* trace with the admissible estimate
  trace_manhattan.tex  table rows: A* trace with the Manhattan estimate
  trace_dijkstra.tex   table rows: Dijkstra trace on the eight-city graph
  trace_greedy.tex     table rows: greedy best-first trace on the eight-city graph
  counterexample.tex   the admissible but inconsistent example
  results.txt          a plain-text summary of every run

The .tex files go to output/tex/ and are the figure sources used by the report.

Run:  python3 make_figures.py      (needs only the Python standard library)
"""
import json
import math
import os

from searches import search, undirected, exact_to_goal, haversine_km

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'output')
FIG = os.path.join(OUT, 'tex')
os.makedirs(FIG, exist_ok=True)
summary = []


def write(name, lines):
    with open(os.path.join(FIG, name), 'w', encoding='utf-8') as f:
        f.write('% generated by make_figures.py -- do not edit by hand\n')
        f.write('\n'.join(lines) + '\n')


def num(x, digits=1):
    return f'{x:.{digits}f}'


# ======================================================================
#  1. the district map
# ======================================================================
data = json.load(open(os.path.join(HERE, 'data', 'bangladesh.json')))
coast = data['coast']
co = {k: tuple(v) for k, v in data['districts'].items()}
edges = [(a, b, haversine_km(co[a], co[b])) for a, b in data['edges']]
madj = undirected(edges)
START, GOAL = 'dhaka', 'sylhet'
hmap = lambda v: haversine_km(co[v], co[GOAL])
NAMES = {'coxsbazar': "Cox's Bazar", 'chapainawabganj': 'Chapainawabganj'}
pretty = lambda n: NAMES.get(n, n.capitalize())

runs = {m: search(madj, START, GOAL, hmap, m, trace=(m == 'astar'))
        for m in ('dijkstra', 'greedy', 'astar')}
exact = exact_to_goal(madj, GOAL)
admissible = all(hmap(v) <= exact[v] + 1e-9 for v in co)
consistent = all(hmap(a) <= w + hmap(b) + 1e-9 for a in madj for b, w in madj[a])
summary.append(f'map: {len(co)} districts, {len(edges)} edges, '
               f'straight-line h admissible={admissible} consistent={consistent}')
for m, r in runs.items():
    summary.append(f'  {m:8s} expanded {len(r["order"]):2d}  cost {num(r["cost"])} km  '
                   f'path {" > ".join(map(pretty, r["path"]))}')
summary.append(f'  h(Dhaka) = {num(hmap(START))} km, exact remaining = {num(exact[START])} km')

LON0, LAT0 = 88.0, 20.7


def xy(p):
    return f'({num(p[0] - LON0, 3)},{num(p[1] - LAT0, 3)})'


def map_base(scale):
    """Border, edges and district dots, drawn at `scale` cm per degree."""
    L = [f'\\begin{{tikzpicture}}[x={num(0.92 * scale, 3)}cm, y={num(scale, 3)}cm]']
    L.append('  \\fill[maplandfill] ' + ' -- '.join(xy(p) for p in coast) + ' -- cycle;')
    L.append('  \\draw[mapborder] ' + ' -- '.join(xy(p) for p in coast) + ' -- cycle;')
    for n, p in co.items():
        L.append(f'  \\coordinate ({n}) at {xy(p)};')
    L.append('  \\foreach \\a/\\b in {' +
             ', '.join(f'{a}/{b}' for a, b, _ in edges) + '}')
    L.append('    {\\draw[mapedge] (\\a) -- (\\b);}')
    L.append('  \\foreach \\n in {' + ', '.join(co) + '}')
    L.append('    {\\node[mapdot] at (\\n) {};}')
    return L


def map_ends(L, labels=True):
    L.append(f'  \\node[mapstart] at ({START}) {{}};')
    L.append(f'  \\node[mapgoal] at ({GOAL}) {{}};')
    if labels:
        L.append(f'  \\node[maplabel, anchor=north east] at ({START}) {{Dhaka}};')
        L.append(f'  \\node[maplabel, anchor=south west] at ({GOAL}) {{Sylhet}};')


# full map, for Section 2
L = map_base(1.55)
map_ends(L)
L.append('\\end{tikzpicture}')
write('map_graph.tex', L)

# three panels, for Section 5
COLOR = {'dijkstra': 'algdijkstra', 'greedy': 'alggreedy', 'astar': 'algastar'}
TITLE = {'dijkstra': "Dijkstra's algorithm", 'greedy': 'Greedy best-first search',
         'astar': 'A* search'}
L = []
for k, m in enumerate(('dijkstra', 'greedy', 'astar')):
    r = runs[m]
    L.append(f'\\begin{{subfigure}}[t]{{0.32\\textwidth}}\\centering')
    L += ['  ' + s for s in map_base(0.78)]
    L.append('    \\foreach \\n in {' + ', '.join(r['order']) + '}')
    L.append(f'      {{\\node[mapdot, fill={COLOR[m]}!55, draw={COLOR[m]}] at (\\n) {{}};}}')
    L.append(f'    \\draw[maproute, draw={COLOR[m]}] ' +
             ' -- '.join(f'({n})' for n in r['path']) + ';')
    map_ends(L, labels=False)
    L.append('  \\end{tikzpicture}')
    L.append(f'  \\caption{{{TITLE[m]}: {len(r["order"])} districts expanded, '
             f'route {num(r["cost"])}\\,km.}}')
    L.append(f'  \\label{{fig:map-{m}}}')
    L.append('\\end{subfigure}' + ('\\hfill' if k < 2 else ''))
write('map_panels.tex', L)

# A* on the map, as table rows
L = []
for i, u in enumerate(runs['astar']['order'], 1):
    g = runs['astar']['g'][u]
    L.append(f'{i} & {pretty(u)} & {num(g)} & {num(hmap(u))} & {num(g + hmap(u))} \\\\')
