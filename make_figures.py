# ======================================================================
#  4. admissible but inconsistent: the closed set loses the optimum
# ======================================================================
CE = [('s', 'a', 1), ('a', 'c', 1), ('s', 'b', 1), ('b', 'c', 2), ('c', 't', 3)]
