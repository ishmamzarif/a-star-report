GW, GH = 11, 7
water = {(c, r) for c in (5, 6) for r in range(GH)} - {(5, 5), (6, 5)}   # bridge on row 5
mud = {(7, 3), (8, 3), (7, 4), (8, 4)}
blocked = {(3, 3), (2, 3), (2, 2), (1, 6), (10, 4), (4, 4), (8, 2), (8, 0), (3, 0)}
tiles = {(c, r) for c in range(GW) for r in range(GH)} - blocked
cost = lambda v: 5 if v in water else (3 if v in mud else 1)
tadj = {v: [((v[0] + dc, v[1] + dr), cost((v[0] + dc, v[1] + dr)))
            for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)) if (v[0] + dc, v[1] + dr) in tiles]
        for v in tiles}
rg = search(tadj, (0, 1), (10, 2), lambda v: 0, 'dijkstra')
straight = [(c, 1) for c in range(11)] + [(10, 2)]
summary.append(f'game map: cheapest route {len(rg["path"]) - 1} steps, cost {int(rg["cost"])}; '
               f'straight route {len(straight) - 1} steps, cost {sum(cost(v) for v in straight[1:])}')

