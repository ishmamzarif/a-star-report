summary.append(f'  closed set: order {"".join(r1["order"])} path {"".join(r1["path"])} cost {int(r1["cost"])}')
summary.append(f'  reopening:  order {"".join(r2["order"])} path {"".join(r2["path"])} cost {int(r2["cost"])}')
CPOS = dict(s=(0, 0), a=(1.8, 1.0), b=(1.8, -1.0), c=(3.6, 0), t=(5.4, 0))
