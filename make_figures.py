# ======================================================================
#  6. the eight-city graph seen from above at an angle (isometric)
# ======================================================================
def iso(x, y):
    """An affine isometric camera, in cm."""
    return (0.39 * x + 0.10 * y) * 1.08, (-0.065 * x + 0.29 * y) * 1.08


def iso_view(closed, route, color, hvals, grid):
    pts = {v: iso(*GRIDPOS[v]) for v in GRIDPOS}
    L = ['\\begin{tikzpicture}[x=1cm, y=1cm]']
    plate = [iso(-1, -1), iso(17, -1), iso(17, 9), iso(-1, 9)]
    sh = ' -- '.join(f'({num(x, 3)},{num(y - 0.15, 3)})' for x, y in plate)
    L.append(f'  \\fill[black!10] {sh} -- cycle;')
    L.append('  \\draw[draw=rblue!14, fill=rbluelt!35, line width=0.6pt] ' +
             ' -- '.join(f'({num(x, 3)},{num(y, 3)})' for x, y in plate) + ' -- cycle;')
    if grid:
        for gx in range(0, 17):
            (x1, y1), (x2, y2) = iso(gx, 0), iso(gx, 8)
            L.append(f'  \\draw[black!{19 if gx % 4 == 0 else 10}, line width=0.3pt] '
                     f'({num(x1, 3)},{num(y1, 3)}) -- ({num(x2, 3)},{num(y2, 3)});')
        for gy in range(0, 9):
            (x1, y1), (x2, y2) = iso(0, gy), iso(16, gy)
            L.append(f'  \\draw[black!{19 if gy % 4 == 0 else 10}, line width=0.3pt] '
                     f'({num(x1, 3)},{num(y1, 3)}) -- ({num(x2, 3)},{num(y2, 3)});')
    for v, (x, y) in pts.items():
        L.append(f'  \\coordinate ({v}) at ({num(x, 3)},{num(y, 3)});')
    onroute = set(zip(route, route[1:])) | set(zip(route[1:], route))
    for a, b, w in SE:
        style = f'draw={color}, line width=2pt' if (a, b) in onroute else 'draw=rblue!55, line width=1pt'
        L.append(f'  \\draw[{style}] ({a}) -- ({b});')
    for a, b, w in SE:
        L.append(f'  \\node[isoweight] at ($({a})!0.5!({b})$) {{{w}}};')
    for v in GRIDPOS:
        if v in route:
            fill, stroke = f'{color}!15', color
        elif v in closed:
            fill, stroke = 'gray!30', 'gray'
        else:
            fill, stroke = 'white', 'rblue!70'
        if v == 'D':
            stroke = 'algastar'
        if v == 'S':
            stroke = 'cbRed'
        L.append(f'  \\isodisc{{{v}}}{{{fill}}}{{{stroke}}}{{{v}}}{{{hvals[v]}}}')
    L.append('\\end{tikzpicture}')
    return L


r_o = search(sadj, 'D', 'S', H_ORIG.get, 'astar')
