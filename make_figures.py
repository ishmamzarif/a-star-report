# ======================================================================
#  2. the 16 x 10 grid with a U-shaped wall
# ======================================================================
W, H = 16, 10
GS, GG = (1, 4), (14, 6)
walls = ({(12, r) for r in range(3, 8)} | {(c, 3) for c in range(4, 13)}
         | {(c, 7) for c in range(4, 13)})
free = {(c, r) for c in range(W) for r in range(H)} - walls
gadj = {v: [((v[0] + dc, v[1] + dr), 1) for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1))
            if (v[0] + dc, v[1] + dr) in free] for v in free}
manh = lambda v: abs(v[0] - GG[0]) + abs(v[1] - GG[1])
gruns = {m: search(gadj, GS, GG, manh, m) for m in ('dijkstra', 'greedy', 'astar')}
summary.append(f'grid: {W} x {H}, {len(walls)} wall cells, 4-connected, unit cost, '
               f'Manhattan h')
for m, r in gruns.items():
    frontier = set(r['g']) - set(r['order'])
    summary.append(f'  {m:8s} expanded {len(r["order"]):3d}  frontier {len(frontier):3d}  '
                   f'cost {int(r["cost"])}')


